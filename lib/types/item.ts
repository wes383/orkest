export type Priority = "low" | "medium" | "high" | "urgent";

export interface Project {
  id: string;
  userId: string;
  name: string;
  color?: string;
  createdAt: Date;
  updatedAt: Date;
}

export type ItemStatus =
  | "active"
  | "in_progress"
  | "completed"
  | "cancelled"
  | "skipped";

export interface OccurrenceNotification {
  date: string;
  notificationId: string;
}

export interface Reminder {
  id: string;
  minutesBefore: number;
  method: "push" | "email";
  onesignalNotificationId?: string;
  /** For all-day events: the time of day when the reminder should trigger, e.g. "10:30" */
  triggerTime?: string;
  /** For all-day events: how many days/weeks before the event */
  dayOffset?: number;
  /** For recurring events: notification IDs for each scheduled occurrence */
  occurrenceNotifications?: OccurrenceNotification[];
}

export interface Item {
  id: string;
  uid: string;
  title: string;
  description?: string;
  time: {
    start?: Date;
    end?: Date;
    due?: Date;
    allDay?: boolean;
    timezone?: string;
  };
  actual: {
    start?: Date;
    end?: Date;
  };
  status: ItemStatus;
  completedAt?: Date;
  progress?: number;
  priority?: Priority;
  ai?: {
    sourceText?: string;
    autoGenerated?: boolean;
    reasoning?: string;
    suggestedSubtasks?: string[];
  };
  recurrence?: {
    type: "none" | "daily" | "weekly" | "monthly" | "yearly";
    interval?: number;
    daysOfWeek?: number[];
    endDate?: Date;
    count?: number;
    bysetpos?: number;
  };
  rrule?: string;
  exdates?: Date[];
  completedOccurrences?: Date[];
  reopenedOccurrences?: Date[];
  deferredUntil?: Date;
  dismissedTodayDates?: string[];
  plannedTodayDates?: string[];
  nowOverrideDate?: string;
  projectId?: string;
  parentId?: string;
  tags?: string[];
  orderIndex?: number;
  reminders?: Reminder[];
  estimateMinutes?: number;
  actualMinutes?: number;
  focusSessions?: number;
  createdAt: Date;
  updatedAt: Date;
  deletedAt?: Date;
}
