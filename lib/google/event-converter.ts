/**
 * Converts between Orkest's ManualItemRecord and Google Calendar Event resources.
 */

import { dayjs } from "../dayjs";
import type { ManualItemRecord } from "../types/all-page";
import type { ItemStatus } from "../types/item";
import { formatRecurrenceForGoogle, parseGoogleRecurrenceToOrkest } from "./rrule-converter";

export type GoogleEvent = {
  id?: string;
  summary: string;
  description?: string;
  start?: GoogleEventDateTime;
  end?: GoogleEventDateTime;
  status?: "confirmed" | "tentative" | "cancelled";
  recurrence?: string[];
  extendedProperties?: {
    private?: Record<string, string>;
  };
  transparency?: "opaque" | "transparent";
  reminders?: {
    useDefault: boolean;
    overrides?: Array<{
      method: "popup" | "email";
      minutes: number;
    }>;
  };
};

export type GoogleEventDateTime = {
  date?: string;       // YYYY-MM-DD for all-day events
  dateTime?: string;   // ISO 8601 for timed events
  timeZone?: string;
};

const ORKEST_PRIVATE_PREFIX = "orkest_";
const ORKEST_STATUS_KEY = `${ORKEST_PRIVATE_PREFIX}status`;
const ORKEST_AUTO_END_KEY = `${ORKEST_PRIVATE_PREFIX}auto_end`;

/**
 * Convert an Orkest ManualItemRecord to a Google Calendar Event resource.
 */
export function itemToGoogleEvent(item: ManualItemRecord): GoogleEvent {
  const event: GoogleEvent = {
    summary: item.title,
    description: item.description || undefined,
    status: mapStatusToGoogle(item.status),
    extendedProperties: {
      private: {
        [`${ORKEST_PRIVATE_PREFIX}item_id`]: item.id,
        [`${ORKEST_PRIVATE_PREFIX}uid`]: item.uid || item.id,
        ...(item.status ? { [ORKEST_STATUS_KEY]: item.status } : {}),
      },
    },
  };

  // Reminders are not synced — each platform manages its own notifications independently

  // Set dates
  if (item.startDate || item.endDate) {
    const { start, end, autoGeneratedEnd } = buildGoogleDateTimes(item);
    event.start = start;
    event.end = end;
    event.extendedProperties!.private![ORKEST_AUTO_END_KEY] = autoGeneratedEnd ? "true" : "false";
  }

  // Set recurrence
  const recurrence = formatRecurrenceForGoogle(item.rrule, item.exdates);
  if (recurrence) {
    event.recurrence = recurrence;
  }

  // Set transparency for completed/cancelled items
  if (item.status === "completed" || item.status === "cancelled" || item.status === "skipped") {
    event.transparency = "transparent";
  }

  console.log("[GoogleSync DEBUG] itemToGoogleEvent:", JSON.stringify({
    title: event.summary,
    start: event.start,
    end: event.end,
    recurrence: event.recurrence,
    itemTimezone: item.timezone,
    itemStartDate: item.startDate,
    itemStartTime: item.startTime,
  }, null, 2));

  return event;
}

/**
 * Convert a Google Calendar Event to an Orkest ManualItemRecord partial.
 * Used for creating or updating items from Google sync.
 */
export function googleEventToItemPatch(event: GoogleEvent): Partial<ManualItemRecord> {
  const patch: Partial<ManualItemRecord> = {};

  if (event.summary !== undefined) {
    patch.title = event.summary;
  }

  if (event.description !== undefined) {
    patch.description = event.description || undefined;
  }

  // Parse dates
  if (event.start) {
    const { startDate, startTime, allDay } = parseGoogleDateTime(event.start);
    patch.startDate = startDate;
    patch.startTime = startTime;
    patch.allDay = allDay;
    if (event.start.timeZone) {
      patch.timezone = event.start.timeZone;
    }
  }

  if (event.end) {
    const { startDate: endDate, startTime: endTime } = parseGoogleDateTime(event.end, true);
    if (!isAutoGeneratedGoogleEnd(event)) {
      patch.endDate = endDate;
      patch.endTime = endTime;
    }
  }

  // Parse recurrence
  if (event.recurrence) {
    const { rrule, exdates } = parseGoogleRecurrenceToOrkest(event.recurrence);
    patch.rrule = rrule ?? undefined;
    patch.exdates = exdates.length > 0 ? exdates : undefined;
  }

  // Reminders are not synced — each platform manages its own notifications independently

  // Map status — prefer the original Orkest status stored in extendedProperties
  if (event.status === "cancelled") {
    patch.status = "cancelled";
    return patch;
  }

  const originalStatus = event.extendedProperties?.private?.[ORKEST_STATUS_KEY];
  if (originalStatus && ["active", "in_progress", "completed", "cancelled", "skipped"].includes(originalStatus)) {
    patch.status = originalStatus as ItemStatus;
  } else if (event.status) {
    patch.status = mapStatusFromGoogle(event.status);
  }

  return patch;
}

function buildGoogleDateTimes(item: ManualItemRecord): {
  start: GoogleEventDateTime;
  end: GoogleEventDateTime;
  autoGeneratedEnd: boolean;
} {
  const tz = item.timezone || undefined;

  if (item.allDay || !item.startTime) {
    const startDate = item.startDate || item.endDate || "";
    const endDate = item.endDate || startDate;
    return {
      start: { date: startDate },
      end: { date: dayjs(endDate).add(1, "day").format("YYYY-MM-DD") },
      autoGeneratedEnd: false,
    };
  }

  const start: GoogleEventDateTime = {};
  const end: GoogleEventDateTime = {};
  let autoGeneratedEnd = false;

  if (item.startDate) {
    if (item.startTime) {
      const dt = `${item.startDate}T${item.startTime}:00`;
      // Use local timezone offset (e.g. +08:00) instead of UTC "Z" suffix.
      // Google Calendar uses the dateTime's date component as the DTSTART
      // anchor for recurring event BYDAY evaluation. When the offset is UTC
      // ("Z"), the UTC date may differ from the local date for timezones
      // east of UTC, causing BYDAY to match the wrong days.
      start.dateTime = tz ? dayjs.tz(dt, tz).format() : dayjs(dt).format();
      start.timeZone = tz;
      console.log("[GoogleSync DEBUG] buildGoogleDateTimes start:", {
        inputDt: dt,
        tz,
        hasTz: !!tz,
        outputDateTime: start.dateTime,
        outputTimeZone: start.timeZone,
        systemTz: Intl.DateTimeFormat().resolvedOptions().timeZone,
      });
    } else {
      start.date = item.startDate;
    }
  }

  if (item.endDate && item.endTime) {
    const dt = `${item.endDate}T${item.endTime}:00`;
    end.dateTime = tz ? dayjs.tz(dt, tz).format() : dayjs(dt).format();
    end.timeZone = tz;
  } else if (item.startDate && item.startTime) {
    // Default end to 1 hour after start if no end specified
    const startMoment = tz
      ? dayjs.tz(`${item.startDate}T${item.startTime}:00`, tz)
      : dayjs(`${item.startDate}T${item.startTime}:00`);
    end.dateTime = startMoment.add(1, "hour").format();
    end.timeZone = tz;
    autoGeneratedEnd = true;
  }

  return { start, end, autoGeneratedEnd };
}

function isAutoGeneratedGoogleEnd(event: GoogleEvent): boolean {
  if (event.extendedProperties?.private?.[ORKEST_AUTO_END_KEY] !== "true") {
    return false;
  }
  if (!event.start?.dateTime || !event.end?.dateTime) {
    return false;
  }

  const start = parseGoogleDateTime(event.start);
  const end = parseGoogleDateTime(event.end);
  if (!start.startDate || !start.startTime || !end.startDate || !end.startTime) {
    return false;
  }

  const startMoment = dayjs(`${start.startDate}T${start.startTime}:00`);
  const endMoment = dayjs(`${end.startDate}T${end.startTime}:00`);
  return endMoment.diff(startMoment, "minute") === 60;
}

function parseGoogleDateTime(dt: GoogleEventDateTime, isEndDate = false): {
  startDate?: string;
  startTime?: string;
  allDay: boolean;
} {
  if (dt.date) {
    // Google uses exclusive end dates for all-day events, so subtract 1 day
    const date = isEndDate ? dayjs(dt.date).subtract(1, "day").format("YYYY-MM-DD") : dt.date;
    return { startDate: date, allDay: true };
  }

  if (dt.dateTime) {
    // Extract wall-clock time from the event's datetime.
    // When an offset or "Z" is present, strip it and parse in the event's timezone
    // (or local time) to get the original wall-clock time.
    // e.g. "2026-07-22T14:00:00-04:00" with tz "America/New_York" → 14:00, not 18:00.
    const hasOffset = /[+-]\d{2}:\d{2}$/.test(dt.dateTime) || dt.dateTime.endsWith("Z");
    let m: ReturnType<typeof dayjs>;
    if (hasOffset) {
      // Strip the offset/Z to get the raw wall-clock string, then parse in the event's timezone
      const stripped = dt.dateTime.replace(/([+-]\d{2}:\d{2}|Z)$/, "");
      m = dt.timeZone ? dayjs.tz(stripped, dt.timeZone) : dayjs(stripped);
    } else {
      m = dt.timeZone ? dayjs.tz(dt.dateTime, dt.timeZone) : dayjs(dt.dateTime);
    }
    return {
      startDate: m.format("YYYY-MM-DD"),
      startTime: m.format("HH:mm"),
      allDay: false,
    };
  }

  return { allDay: false };
}

function mapStatusToGoogle(status?: ItemStatus): GoogleEvent["status"] {
  switch (status) {
    case "cancelled":
      return "cancelled";
    case "completed":
    case "skipped":
    case "in_progress":
    case "active":
    default:
      return "confirmed";
  }
}

function mapStatusFromGoogle(status: GoogleEvent["status"]): ItemStatus {
  switch (status) {
    case "cancelled":
      return "cancelled";
    case "tentative":
    case "confirmed":
    default:
      return "active";
  }
}

/**
 * Extract the Orkest item ID from a Google Event's extended properties.
 */
export function getOrkestItemIdFromEvent(event: GoogleEvent): string | null {
  return event.extendedProperties?.private?.[`${ORKEST_PRIVATE_PREFIX}item_id`] ?? null;
}
